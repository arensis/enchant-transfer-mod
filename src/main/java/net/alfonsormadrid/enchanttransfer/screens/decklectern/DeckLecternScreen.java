package net.alfonsormadrid.enchanttransfer.screens.decklectern;

import net.alfonsormadrid.enchanttransfer.EnchantTransferMod;
import net.alfonsormadrid.enchanttransfer.blocks.decklectern.LampState;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.client.gui.screens.inventory.AbstractContainerScreen;
import net.minecraft.client.renderer.RenderPipelines;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.player.Inventory;

/**
 * GUI screen for the Deck Lectern: 3 deck slots, a lamp under each slot
 * (same colours as the block) and the amethyst gem showing whether the
 * lectern is active.  Background: {@code deck_lectern_gui.png}, generated by
 * {@code scripts/gen_deck_lectern_assets.py}.
 */
@Environment(EnvType.CLIENT)
public class DeckLecternScreen extends AbstractContainerScreen<DeckLecternScreenHandler> {

    private static final Identifier TEXTURE =
            Identifier.fromNamespaceAndPath(EnchantTransferMod.MOD_ID, "textures/gui/container/deck_lectern_gui.png");

    private static final int BG_W = 176, BG_H = 166;

    // Lamp bar under each deck slot (slot item at DECK_SLOT_X, 16 px wide)
    private static final int LAMP_Y = 48, LAMP_W = 12, LAMP_H = 3;
    private static final int LAMP_NONE = 0xFF4A1E10, LAMP_EMPTY = 0xFFFFF1B8, LAMP_FULL = 0xFF2BDC6B;

    // Amethyst gem, right of the slots
    private static final int GEM_X = 146, GEM_Y = 29, GEM_SIZE = 10;
    private static final int GEM_ON = 0xFFD2A2FF, GEM_ON_CORE = 0xFFF6E0FF, GEM_OFF = 0xFF3F3452;

    private static final int TITLE_COL = 0xFF3A2008;

    public DeckLecternScreen(DeckLecternScreenHandler handler, Inventory inventory, Component title) {
        super(handler, inventory, title, BG_W, BG_H);
    }

    @Override
    protected void init() {
        super.init();
        titleLabelX = (imageWidth - font.width(title)) / 2;
    }

    @Override
    protected void extractLabels(GuiGraphicsExtractor ctx, int mouseX, int mouseY) {
        ctx.text(font, title, titleLabelX, titleLabelY, TITLE_COL, false);
    }

    @Override
    public void extractBackground(GuiGraphicsExtractor ctx, int mouseX, int mouseY, float delta) {
        super.extractBackground(ctx, mouseX, mouseY, delta);
        int gx = (width - imageWidth) / 2;
        int gy = (height - imageHeight) / 2;
        ctx.blit(RenderPipelines.GUI_TEXTURED, TEXTURE, gx, gy, 0f, 0f, imageWidth, imageHeight, 256, 256);

        for (int i = 0; i < DeckLecternScreenHandler.DECK_SLOT_X.length; i++) {
            int x = gx + DeckLecternScreenHandler.DECK_SLOT_X[i] + (16 - LAMP_W) / 2;
            ctx.fill(x, gy + LAMP_Y, x + LAMP_W, gy + LAMP_Y + LAMP_H, lampColor(menu.lampState(i)));
        }

        int gemX = gx + GEM_X, gemY = gy + GEM_Y;
        boolean active = menu.isActive();
        ctx.fill(gemX, gemY, gemX + GEM_SIZE, gemY + GEM_SIZE, active ? GEM_ON : GEM_OFF);
        if (active) {
            ctx.fill(gemX + 3, gemY + 3, gemX + GEM_SIZE - 3, gemY + GEM_SIZE - 3, GEM_ON_CORE);
        }
    }

    @Override
    protected void extractTooltip(GuiGraphicsExtractor ctx, int mouseX, int mouseY) {
        super.extractTooltip(ctx, mouseX, mouseY);
        int gx = (width - imageWidth) / 2;
        int gy = (height - imageHeight) / 2;
        if (mouseX >= gx + GEM_X && mouseX < gx + GEM_X + GEM_SIZE
                && mouseY >= gy + GEM_Y && mouseY < gy + GEM_Y + GEM_SIZE) {
            String key = menu.isActive() ? "enchanttransfer.deck_lectern.active"
                    : menu.isEnabled() ? "enchanttransfer.deck_lectern.no_cards"
                    : "enchanttransfer.deck_lectern.inactive";
            ctx.setTooltipForNextFrame(font, Component.translatable(key), mouseX, mouseY);
        }
    }

    private static int lampColor(LampState state) {
        return switch (state) {
            case NONE -> LAMP_NONE;
            case EMPTY -> LAMP_EMPTY;
            case FULL -> LAMP_FULL;
        };
    }
}

package net.alfonsormadrid.enchanttransfer.renderers;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.alfonsormadrid.enchanttransfer.EnchantTransferMod;
import com.mojang.math.Axis;
import net.alfonsormadrid.enchanttransfer.blocks.decklectern.DeckLecternBlock;
import net.alfonsormadrid.enchanttransfer.blocks.decklectern.DeckLecternBlockEntity;
import net.alfonsormadrid.enchanttransfer.renderers.state.DeckLecternRenderState;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.blockentity.BlockEntityRenderer;
import net.minecraft.client.renderer.blockentity.BlockEntityRendererProvider;
import net.minecraft.client.renderer.feature.ModelFeatureRenderer;
import net.minecraft.client.renderer.item.ItemModelResolver;
import net.minecraft.client.renderer.item.ItemStackRenderState;
import net.minecraft.client.renderer.rendertype.RenderType;
import net.minecraft.client.renderer.rendertype.RenderTypes;
import net.minecraft.client.renderer.state.level.CameraRenderState;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.core.Direction;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemDisplayContext;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.phys.Vec3;

/**
 * BER for the Deck Lectern — draws the decks lying face up on the tilted
 * tray, and the amethyst's halo while the lectern is lit.  Base, tray, glass
 * bell, lamps and crystal are in the baked block model.
 * <p>
 * The halo is a single camera-facing quad: crossed translucent planes in the
 * model intersected each other and flickered as translucent sorting changed.
 * <p>
 * Tray geometry mirrors {@code models/block/deck_lectern.json} (generated by
 * {@code scripts/gen_deck_lectern_assets.py}): centred at (8, 7.6, 8) px,
 * tilted {@value #TRAY_TILT}° about X (back raised).
 */
public class DeckLecternRenderer
        implements BlockEntityRenderer<DeckLecternBlockEntity, DeckLecternRenderState> {

    private static final float PX = 1f / 16f;
    private static final float TRAY_TILT = 18f;
    private static final float TRAY_X = 8f, TRAY_Y = 7.6f, TRAY_Z = 8f;
    /** Deck centres on the tray, in px relative to the tray centre. */
    private static final float[] DECK_X = {-4.4f, -0.1f, 4.2f};
    private static final float DECK_Y = 0.5f + 0.72f;   // tray top + half the scaled deck thickness
    private static final float DECK_Z = -2.0f;
    /** The deck item model is 10×14×4 px; at this scale it lies 3.6 px wide on the tray. */
    private static final float DECK_SCALE = 0.36f;

    private static final Identifier HALO_TEXTURE =
            Identifier.fromNamespaceAndPath(EnchantTransferMod.MOD_ID, "textures/block/deck_lectern_halo.png");
    /** Halo centre (px, block space) — on the amethyst crystal — and half size in blocks. */
    private static final float HALO_Y = 16.8f;
    private static final float HALO_HALF = 0.32f;
    private static final int FULL_LIGHT = 0xF000F0;

    private final ItemModelResolver itemModelResolver;

    public DeckLecternRenderer(BlockEntityRendererProvider.Context ctx) {
        this.itemModelResolver = ctx.itemModelResolver();
    }

    @Override
    public DeckLecternRenderState createRenderState() {
        return new DeckLecternRenderState();
    }

    @Override
    public void extractRenderState(DeckLecternBlockEntity entity,
                                   DeckLecternRenderState state,
                                   float tickDelta,
                                   Vec3 cameraPos,
                                   ModelFeatureRenderer.CrumblingOverlay crumbling) {
        BlockEntityRenderer.super.extractRenderState(entity, state, tickDelta, cameraPos, crumbling);
        state.facing = entity.getBlockState().getValue(DeckLecternBlock.FACING);
        state.lit = DeckLecternBlock.isLit(entity.getBlockState());
        int seed = (int) entity.getBlockPos().asLong();
        for (int i = 0; i < state.decks.length; i++) {
            ItemStack stack = entity.getItems().get(i);
            if (stack.isEmpty()) {
                state.decks[i].clear();
            } else {
                itemModelResolver.updateForTopItem(state.decks[i], stack, ItemDisplayContext.NONE,
                        entity.getLevel(), null, seed + i);
            }
        }
    }

    @Override
    public void submit(DeckLecternRenderState state,
                       PoseStack matrices,
                       SubmitNodeCollector queue,
                       CameraRenderState cameraState) {
        if (state.lit) {
            submitHalo(matrices, queue, cameraState);
        }
        for (int i = 0; i < state.decks.length; i++) {
            ItemStackRenderState deck = state.decks[i];
            if (deck.isEmpty()) continue;

            matrices.pushPose();
            // Block centre, then the same rotation the blockstate applies to the model
            matrices.translate(0.5f, 0.5f, 0.5f);
            matrices.mulPose(Axis.YP.rotationDegrees(-modelYRotation(state.facing)));
            // Onto the tilted tray
            matrices.translate((TRAY_X - 8f) * PX, (TRAY_Y - 8f) * PX, (TRAY_Z - 8f) * PX);
            matrices.mulPose(Axis.XP.rotationDegrees(TRAY_TILT));
            matrices.translate(DECK_X[i] * PX, DECK_Y * PX, DECK_Z * PX);
            // Lay the deck face up, its top towards the back of the tray
            matrices.mulPose(Axis.XP.rotationDegrees(-90f));
            matrices.scale(DECK_SCALE, DECK_SCALE, DECK_SCALE);
            deck.submit(matrices, queue, state.lightCoords, OverlayTexture.NO_OVERLAY, 0);
            matrices.popPose();
        }
    }

    private static void submitHalo(PoseStack matrices, SubmitNodeCollector queue, CameraRenderState cameraState) {
        RenderType layer = RenderTypes.entityTranslucentEmissive(HALO_TEXTURE);
        matrices.pushPose();
        matrices.translate(0.5f, HALO_Y * PX, 0.5f);
        matrices.mulPose(cameraState.orientation);
        queue.submitCustomGeometry(matrices, layer, (entry, vc) -> {
            vertex(entry, vc, -HALO_HALF, -HALO_HALF, 0f, 1f);
            vertex(entry, vc, HALO_HALF, -HALO_HALF, 1f, 1f);
            vertex(entry, vc, HALO_HALF, HALO_HALF, 1f, 0f);
            vertex(entry, vc, -HALO_HALF, HALO_HALF, 0f, 0f);
        });
        matrices.popPose();
    }

    private static void vertex(PoseStack.Pose entry, VertexConsumer vc, float x, float y, float u, float v) {
        vc.addVertex(entry, x, y, 0f).setColor(1f, 1f, 1f, 1f).setUv(u, v)
                .setOverlay(OverlayTexture.NO_OVERLAY).setLight(FULL_LIGHT).setNormal(entry, 0f, 0f, 1f);
    }

    /** Blockstate "y" for each facing (see blockstates/deck_lectern.json). */
    private static float modelYRotation(Direction facing) {
        return switch (facing) {
            case EAST -> 90f;
            case SOUTH -> 180f;
            case WEST -> 270f;
            default -> 0f;
        };
    }
}
